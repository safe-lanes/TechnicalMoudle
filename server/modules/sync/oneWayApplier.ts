/**
 * One-Way Sync Applier — Upserts rows by UUID for one-way sync tables.
 *
 * Used for:
 * - SHIP_ONLY tables: ship pushes -> shore overwrites
 * - ONE_WAY_SHORE_TO_SHIP tables: shore pushes -> ship overwrites
 *
 * Uses raw SQL for dynamic table names since Drizzle ORM requires static table refs.
 */

import { getPool } from '../../db';
import { getTableSyncConfig, getIdentityColumn } from '../../../shared/syncConfig';
import { syncDiag } from './syncDiagLogger';
import { safeParseDate } from '../running-hours/utils/rhValidation';

interface ApplyResult {
  inserted: number;
  updated: number;
  softDeleted: number;
  errors: Array<{ rowIndex: number; error: string }>;
}

// ── Column metadata cache (schema-aware id/JSON handling) ──

export interface ColumnMeta {
  identityAlwaysCols: Set<string>;
  jsonCols: Set<string>;
  allCols: Set<string>;
  arrayCols: Set<string>;
}

const columnMetaCache = new Map<string, ColumnMeta>();

/**
 * Get column metadata for a table — caches auto-generated identity and JSON/JSONB info.
 * identityAlwaysCols includes BOTH 'GENERATED ALWAYS' AND 'GENERATED BY DEFAULT' columns
 * to prevent auto-increment PK conflicts during ship-shore sync.
 * Exported for reuse in syncEngine.ts (applyFieldLog JSON coercion).
 */
export async function getColumnMeta(pool: any, tableName: string): Promise<ColumnMeta> {
  if (columnMetaCache.has(tableName)) return columnMetaCache.get(tableName)!;

  let identityAlwaysCols = new Set<string>();
  let jsonCols = new Set<string>();
  let allCols = new Set<string>();
  let arrayCols = new Set<string>();

  try {
    // Find GENERATED ALWAYS or GENERATED BY DEFAULT AS IDENTITY columns
    // 'a' = ALWAYS, 'd' = BY DEFAULT — both must be excluded from INSERT/UPDATE
    // to avoid PK conflicts when ship sends its auto-increment id to shore (or vice versa)
    const identityResult = await pool.query(
      `SELECT a.attname FROM pg_attribute a
       JOIN pg_class c ON a.attrelid = c.oid
       JOIN pg_namespace n ON c.relnamespace = n.oid
       WHERE n.nspname = 'public' AND c.relname = $1 AND a.attidentity IN ('a', 'd')`,
      [tableName]
    );
    identityAlwaysCols = new Set((identityResult.rows || []).map((r: any) => r.attname));

    // Also detect serial/bigserial columns — these use nextval() DEFAULT but do NOT set
    // attidentity. Without this, ship's auto-increment id (e.g., id=5) is included in
    // INSERT, hitting PK conflict when shore already has its own id=5.
    const serialResult = await pool.query(
      `SELECT a.attname FROM pg_attribute a
       JOIN pg_class c ON a.attrelid = c.oid
       JOIN pg_namespace n ON c.relnamespace = n.oid
       JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
       WHERE n.nspname = 'public' AND c.relname = $1
       AND pg_get_expr(d.adbin, d.adrelid) LIKE 'nextval(%'`,
      [tableName]
    );
    for (const r of (serialResult.rows || [])) {
      identityAlwaysCols.add(r.attname);
    }
  } catch { /* ignore — table may not exist yet */ }

  try {
    // Find json/jsonb columns (for value coercion)
    const jsonResult = await pool.query(
      `SELECT column_name FROM information_schema.columns
       WHERE table_schema = 'public' AND table_name = $1
       AND data_type IN ('json', 'jsonb')`,
      [tableName]
    );
    jsonCols = new Set((jsonResult.rows || []).map((r: any) => r.column_name));
  } catch { /* ignore */ }

  try {
    // All column names — used by the field-log appliers to skip unmapped/absent columns
    // (defense-in-depth) rather than letting an unknown column abort the pull transaction.
    const colResult = await pool.query(
      `SELECT column_name FROM information_schema.columns
       WHERE table_schema = 'public' AND table_name = $1`,
      [tableName]
    );
    allCols = new Set((colResult.rows || []).map((r: any) => r.column_name));
  } catch { /* ignore — table may not exist yet; guard is fail-open when allCols is empty */ }

  try {
    // Postgres array columns (text[] etc.) — values must reach pg as a JS array, not a JSON
    // string, or the insert/update fails with "malformed array literal".
    const arrResult = await pool.query(
      `SELECT column_name FROM information_schema.columns
       WHERE table_schema = 'public' AND table_name = $1 AND data_type = 'ARRAY'`,
      [tableName]
    );
    arrayCols = new Set((arrResult.rows || []).map((r: any) => r.column_name));
  } catch { /* ignore */ }

  const meta = { identityAlwaysCols, jsonCols, allCols, arrayCols };
  columnMetaCache.set(tableName, meta);
  return meta;
}

/**
 * Apply one-way rows — upsert by identity column (UUID).
 *
 * @param tableName - Target table name
 * @param rows - Array of row objects to upsert
 * @returns Counts of inserts, updates, soft-deletes, and any per-row errors
 */
export async function applyOneWayRows(
  tableName: string,
  rows: any[]
): Promise<ApplyResult> {
  if (rows.length === 0) return { inserted: 0, updated: 0, softDeleted: 0, errors: [] };

  syncDiag(`ONE-WAY-APPLY START: ${tableName} — ${rows.length} rows`);

  const config = getTableSyncConfig(tableName);
  if (!config) {
    return {
      inserted: 0, updated: 0, softDeleted: 0,
      errors: [{ rowIndex: -1, error: `Unknown table: ${tableName}` }],
    };
  }

  const identityCol = config.identityColumn;
  // Tables without a UUID identity column use the text PK 'id'
  const lookupColumn = identityCol || 'id';

  const pool = await getPool();

  // Schema-aware column metadata (GENERATED ALWAYS + JSON detection)
  const meta = await getColumnMeta(pool, tableName);

  // Detect composite-key tables: no UUID identity + integer GENERATED PKs that differ
  // between shore and ship. We match by their natural unique key instead of mismatched id.
  const COMPOSITE_KEY_TABLES: Record<string, string[]> = {
    vessel_certificate_applicability: ['vessel_id', 'master_id'],
    vessel_survey_applicability: ['vessel_id', 'master_id'],
    // RBAC permissions — UNIQUE on (role_ruid, menu_muid)
    adm_role_menu_access: ['role_ruid', 'menu_muid'],
    // Vessel department config — UNIQUE on (vessel_id, department)
    vessel_department_config: ['vessel_id', 'department'],
    // Master lists — UNIQUE on (list_type, list_key)
    master_lists: ['list_type', 'list_key'],
    // Job-component links — UNIQUE on (job_id, component_id)
    job_component_links: ['job_id', 'component_id'],
    // Labels config — logical key (config_type, key), no formal UNIQUE constraint
    ship_certificates_labels_config: ['config_type', 'key'],
    ship_surveys_labels_config: ['config_type', 'key'],
    // Alert config — one per vessel
    alert_config: ['vessel_id'],
    // Component class regulatory — match by (component_id, survey_type, classification_society)
    component_class_regulatory: ['component_id', 'survey_type', 'classification_society'],
  };
  const compositeKeys = COMPOSITE_KEY_TABLES[tableName] || null;
  const useCompositeKey = compositeKeys !== null && !identityCol;

  const result: ApplyResult = { inserted: 0, updated: 0, softDeleted: 0, errors: [] };

  for (let i = 0; i < rows.length; i++) {
    const row = rows[i];
    try {
      // Check if this is a soft-delete marker
      const isDeleted = row.is_deleted === true || row.isDeleted === true;

      let existCheck: any;
      let whereClause: string;
      let whereValues: any[];

      if (useCompositeKey) {
        // Composite-key lookup: match by (vessel_id, master_id) etc.
        const conditions: string[] = [];
        whereValues = [];
        let pIdx = 1;
        for (const keyCol of compositeKeys!) {
          const val = row[keyCol] || row[toCamelCase(keyCol)];
          if (!val) {
            break;
          }
          conditions.push(`"${keyCol}" = $${pIdx}`);
          whereValues.push(val);
          pIdx++;
        }
        if (conditions.length !== compositeKeys!.length) {
          // Missing composite key columns — fall back to id lookup
          const lookupValue = row[lookupColumn] || row[toCamelCase(lookupColumn)];
          if (!lookupValue) {
            result.errors.push({ rowIndex: i, error: `Missing composite key columns for "${tableName}"` });
            continue;
          }
          whereClause = `"${lookupColumn}" = $1`;
          whereValues = [lookupValue];
        } else {
          whereClause = conditions.join(' AND ');
        }
        existCheck = await pool.query(
          `SELECT "id" FROM "${tableName}" WHERE ${whereClause} LIMIT 1`,
          whereValues
        );
      } else {
        // Standard single-column lookup
        const lookupValue = row[lookupColumn] || row[toCamelCase(lookupColumn)];
        if (!lookupValue) {
          result.errors.push({ rowIndex: i, error: `Missing identity column "${lookupColumn}"` });
          continue;
        }
        whereClause = `"${lookupColumn}" = $1`;
        whereValues = [lookupValue];
        existCheck = await pool.query(
          `SELECT 1 FROM "${tableName}" WHERE ${whereClause} LIMIT 1`,
          whereValues
        );
      }

      if (existCheck.rows.length > 0) {
        if (isDeleted) {
          // Soft-delete: set is_deleted = true
          await pool.query(
            `UPDATE "${tableName}" SET is_deleted = true, updated_at = NOW() WHERE ${whereClause}`,
            whereValues
          );
          result.softDeleted++;
        } else {
          // Update all columns (excluding PK and generated columns)
          const updatePairs = buildUpdatePairs(row, lookupColumn, meta);
          if (updatePairs.setClauses.length > 0) {
            // Re-parameterize WHERE clause to follow UPDATE SET params
            const offset = updatePairs.values.length;
            const reindexedWhere = whereClause.replace(/\$(\d+)/g, (_, n) => `$${Number(n) + offset}`);
            const updateSQL = `UPDATE "${tableName}" SET ${updatePairs.setClauses.join(', ')}, updated_at = NOW() WHERE ${reindexedWhere}`;
            await pool.query(updateSQL, [...updatePairs.values, ...whereValues]);
          }
          result.updated++;
        }
      } else {
        if (isDeleted) {
          // Row doesn't exist and is deleted — skip
          result.softDeleted++;
          continue;
        }
        // Insert new row — skip the integer PK for composite-key tables so the
        // ship DB generates its own sequence value (avoids PK collisions)
        const insertParts = buildInsertParts(row, meta, useCompositeKey);
        if (insertParts.columns.length > 0) {
          const insertSQL = `INSERT INTO "${tableName}" (${insertParts.columns.join(', ')}) VALUES (${insertParts.placeholders.join(', ')}) ON CONFLICT DO NOTHING`;
          await pool.query(insertSQL, insertParts.values);
          result.inserted++;
        }
      }
    } catch (err: any) {
      syncDiag(`ONE-WAY-APPLY ROW ERROR: ${tableName} row[${i}]: ${err.message.substring(0, 150)}`);
      result.errors.push({ rowIndex: i, error: err.message });
    }
  }

  syncDiag(`ONE-WAY-APPLY DONE: ${tableName} — inserted=${result.inserted}, updated=${result.updated}, deleted=${result.softDeleted}, errors=${result.errors.length}`);

  // Advance sequences for GENERATED ALWAYS identity columns so future
  // INSERTs (via UI or next sync) don't collide with imported integer PKs.
  if (meta.identityAlwaysCols.size > 0) {
    for (const col of Array.from(meta.identityAlwaysCols)) {
      try {
        await pool.query(
          `SELECT setval(pg_get_serial_sequence('"${tableName}"', '${col}'), GREATEST(COALESCE((SELECT MAX("${col}") FROM "${tableName}"), 0), 1))`
        );
      } catch (e: any) {
        console.warn(`[OneWayApplier] Could not advance sequence for ${tableName}.${col}: ${e.message}`);
      }
    }
  }

  // Log detailed error messages so operators can diagnose failures
  if (result.errors.length > 0) {
    console.error(`[OneWayApplier] ${result.errors.length} errors applying ${tableName}:`);
    result.errors.slice(0, 5).forEach((e) =>
      console.error(`  - row ${e.rowIndex}: ${e.error}`)
    );
    if (result.errors.length > 5) {
      console.error(`  ... and ${result.errors.length - 5} more`);
    }
  }

  return result;
}

// ── Helpers ──

/** Convert snake_case to camelCase */
function toCamelCase(str: string): string {
  return str.replace(/_([a-z])/g, (_, c) => c.toUpperCase());
}

/** Convert camelCase to snake_case */
function toSnakeCase(str: string): string {
  // Handle consecutive uppercase (acronyms) correctly:
  // timestampUTC → timestamp_utc, previousRH → previous_rh, completionRHValidated → completion_rh_validated
  return str
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1_$2')   // split acronym from next word: "RHV" → "RH_V"
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')       // split camelCase: "timestamp" + "U" → "timestamp_U"
    .toLowerCase();
}

// Column-name aliases for field_name → DB column where the camel→snake round-trip fails.
// location2 (JS prop) ↔ location_2 (DB col): toSnakeCase only inserts '_' before an uppercase
// letter, never before a digit, so "location2" wrongly stays "location2". A global digit-split
// rule is unsafe — it would break level1/2/3, *_hardware_level*, level2_reviewer_rank_id, etc.
// which round-trip correctly today. So alias the single offender explicitly. Exact-match only.
export const SYNC_COLUMN_ALIASES: Record<string, string> = { location2: 'location_2' };

/** Resolve a field_name to its DB column, honoring SYNC_COLUMN_ALIASES then toSnakeCase. */
export function fieldNameToColumn(fieldName: string): string {
  return SYNC_COLUMN_ALIASES[fieldName] ?? toSnakeCase(fieldName);
}

/** Normalize an array-column value to a JS array so node-postgres serializes a real Postgres
 *  array literal ({...}). Field logs store arrays as JSON strings ('["a","b"]'); provisioning
 *  passes JS arrays. A JSON string inserted into text[] → "malformed array literal". Already-
 *  formatted pg literals ('{...}') and plain scalars pass through unchanged. Handles: JS array,
 *  JSON-string array, pg literal, empty array (→ '{}' via pg), and null. */
export function coerceArrayValue(value: any): any {
  if (value === null || value === undefined) return null;
  if (Array.isArray(value)) return value;
  if (typeof value === 'string') {
    const s = value.trim();
    if (s.startsWith('[')) {
      try { const parsed = JSON.parse(s); if (Array.isArray(parsed)) return parsed; } catch { /* fall through */ }
    }
    return value; // pg array literal '{...}' or unparseable scalar — leave as-is
  }
  return value;
}

// Columns that should not be included in UPDATE (PK + auto-generated timestamps)
const SKIP_UPDATE_COLUMNS = new Set(['id', 'created_at', 'createdAt']);

/** Coerce a value for the correct PostgreSQL column type */
function coerceValue(value: any, snakeKey: string, meta: ColumnMeta): any {
  if (value === null || value === undefined) return null;
  if (meta.jsonCols.has(snakeKey)) {
    // JSON/JSONB column: ensure value is a valid JSON string for PostgreSQL
    if (typeof value === 'string') {
      try { JSON.parse(value); return value; } catch { return JSON.stringify(value); }
    }
    if (typeof value === 'object' && !(value instanceof Date)) {
      return JSON.stringify(value);
    }
    return JSON.stringify(value);
  }
  if (meta.arrayCols.has(snakeKey)) {
    // Postgres array column — return a JS array so pg serializes {...}, not JSON [...]
    return coerceArrayValue(value);
  }
  // Non-JSON: stringify plain objects for TEXT/VARCHAR columns
  if (typeof value === 'object' && !(value instanceof Date)) {
    return JSON.stringify(value);
  }
  return value;
}

/** Build SET clauses for UPDATE */
function buildUpdatePairs(
  row: any,
  identityCol: string,
  meta: ColumnMeta
): { setClauses: string[]; values: any[] } {
  const setClauses: string[] = [];
  const values: any[] = [];
  let paramIndex = 1;

  for (const [key, value] of Object.entries(row)) {
    const snakeKey = toSnakeCase(key);
    // Skip PK, identity, generated-always, and auto-generated columns
    if (SKIP_UPDATE_COLUMNS.has(key) || SKIP_UPDATE_COLUMNS.has(snakeKey)) continue;
    if (meta.identityAlwaysCols.has(key) || meta.identityAlwaysCols.has(snakeKey)) continue;
    if (key === identityCol || snakeKey === identityCol) continue;
    if (key === 'updated_at' || key === 'updatedAt') continue; // We set this ourselves

    setClauses.push(`"${snakeKey}" = $${paramIndex}`);
    values.push(coerceValue(value, snakeKey, meta));
    paramIndex++;
  }

  return { setClauses, values };
}

/** Build columns/placeholders/values for INSERT */
function buildInsertParts(
  row: any,
  meta: ColumnMeta,
  skipIntegerPK: boolean = false
): { columns: string[]; placeholders: string[]; values: any[] } {
  const columns: string[] = [];
  const placeholders: string[] = [];
  const values: any[] = [];
  let paramIndex = 1;

  for (const [key, value] of Object.entries(row)) {
    const snakeKey = toSnakeCase(key);
    // Skip only GENERATED ALWAYS columns (e.g. adm_role_menu_access.id)
    // — do NOT skip regular integer PKs (admn_role_master.id, adm_menumaster_ac.id)
    if (meta.identityAlwaysCols.has(key) || meta.identityAlwaysCols.has(snakeKey)) continue;

    // For composite-key tables, skip the integer PK so the receiving side
    // generates its own sequence value (avoids PK collisions between shore/ship)
    if (skipIntegerPK && (snakeKey === 'id') && typeof value === 'number') continue;

    columns.push(`"${snakeKey}"`);
    placeholders.push(`$${paramIndex}`);
    values.push(coerceValue(value, snakeKey, meta));
    paramIndex++;
  }

  return { columns, placeholders, values };
}

