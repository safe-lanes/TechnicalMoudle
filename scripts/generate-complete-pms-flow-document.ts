function createHeading(text: string, level: HeadingLevel): Paragraph {
  return new Paragraph({
    text: text,
    heading: level,
    spacing: { before: 400, after: 200 },
  });
}

function createParagraph(text: string, bold: boolean = false): Paragraph {
  return new Paragraph({
    children: [new TextRun({ text: text, bold: bold })],
    spacing: { after: 120 },
  });
}

function createBullet(text: string, level: number = 0): Paragraph {
  return new Paragraph({
    children: [new TextRun(text)],
    bullet: { level: level },
    spacing: { after: 60 },
  });
}

function createFlowDiagram(lines: string[]): Paragraph[] {
  return lines.map(
    (line) =>
      new Paragraph({
        children: [
          new TextRun({
            text: line,
            font: "Courier New",
            size: 20,
          }),
        ],
        spacing: { after: 0 },
        indent: { left: 400 },
      })
  );
}

function createTableHeader(cells: string[]): TableRow {
  return new TableRow({
    children: cells.map(
      (cell) =>
        new TableCell({
          children: [
            new Paragraph({
              children: [new TextRun({ text: cell, bold: true, color: "FFFFFF" })],
            }),
          ],
          shading: { type: ShadingType.SOLID, color: "2E74B5" },
          width: { size: 100 / cells.length, type: WidthType.PERCENTAGE },
        })
    ),
  });
}

function createTableRow(cells: string[]): TableRow {
  return new TableRow({
    children: cells.map(
      (cell) =>
        new TableCell({
          children: [new Paragraph({ text: cell, spacing: { after: 0 } })],
          width: { size: 100 / cells.length, type: WidthType.PERCENTAGE },
        })
    ),
  });
}

function pageBreak(): Paragraph {
  return new Paragraph({ children: [new PageBreak()] });
}

