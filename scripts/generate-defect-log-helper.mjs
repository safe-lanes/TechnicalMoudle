// Regenerates the checked-in migration after editing the compatibility source.
// No database connection or mutation is performed by this script.
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const result = await build({
  entryPoints: ['server/modules/defects/paging/compatibility.ts'],
  bundle: true, write: false, format: 'iife', globalName: 'DefectLogCompat',
  platform: 'neutral', target: 'es2020', minify: true, legalComments: 'inline',
});
const bundled = result.outputFiles[0].text;
const timezoneGuard = `if (!["UTC", "Etc/UTC", "GMT"].includes(new Intl.DateTimeFormat().resolvedOptions().timeZone)) {
  throw new Error("Defect Log matching requires UTC database V8 runtime");
}`;
const cacheKey = `__defectLogCompat_${createHash('sha256').update(bundled + timezoneGuard).digest('hex').slice(0, 16)}`;
const notices = await Promise.all([
  ['parse5', 'node_modules/parse5/LICENSE'],
  ['entities', 'node_modules/entities/LICENSE'],
  ['@date-fns/tz', 'node_modules/@date-fns/tz/LICENSE.md'],
].map(async ([name, path]) => `-- ${name}\n${(await readFile(path, 'utf8')).split('\n').map(line => `-- ${line}`).join('\n')}`));
const sql = `-- Generated by scripts/generate-defect-log-helper.mjs; do not hand edit.
-- Approved compatibility helper; no defect records or sync columns are modified.
-- Requires PostgreSQL plv8 on every database hosting this application.
${notices.join('\n--\n')}
CREATE EXTENSION IF NOT EXISTS plv8;
--> statement-breakpoint
CREATE OR REPLACE FUNCTION public.defect_log_matches_v1(row_data jsonb, match_options jsonb)
RETURNS boolean LANGUAGE plv8 STABLE PARALLEL RESTRICTED AS $defect_js$
if (!globalThis.${cacheKey}) {
  ${timezoneGuard}
  ${bundled}
  globalThis.${cacheKey} = DefectLogCompat;
}
return globalThis.${cacheKey}.matchesDefectLog(row_data, match_options);
$defect_js$;
`;
await writeFile('migrations/187_defect_log_matching.sql', sql);
console.log(`Generated Defect Log compatibility migration (${sql.length} bytes)`);
