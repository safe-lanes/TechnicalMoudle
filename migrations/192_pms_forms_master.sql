-- Forms Master Stage 1. Additive, repeatable; existing Form Builder is untouched.
CREATE TABLE IF NOT EXISTS pms_form_groups (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fguuid TEXT NOT NULL UNIQUE,
  group_code TEXT NOT NULL UNIQUE,
  group_name TEXT NOT NULL,
  display_order INTEGER NOT NULL DEFAULT 0,
  seed_key TEXT UNIQUE,
  is_default BOOLEAN NOT NULL DEFAULT false,
  is_deleted BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMP NOT NULL DEFAULT now(),
  updated_at TIMESTAMP NOT NULL DEFAULT now(),
  created_by_uuid TEXT,
  updated_by_uuid TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS pms_form_groups_active_name
  ON pms_form_groups (lower(trim(group_name))) WHERE is_deleted = false;
CREATE TABLE IF NOT EXISTS pms_form_categories (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fcuuid TEXT NOT NULL UNIQUE,
  group_uuid TEXT NOT NULL REFERENCES pms_form_groups(fguuid),
  category_no INTEGER NOT NULL,
  category_name TEXT NOT NULL,
  display_order INTEGER NOT NULL DEFAULT 0,
  seed_key TEXT UNIQUE,
  is_default BOOLEAN NOT NULL DEFAULT false,
  is_deleted BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMP NOT NULL DEFAULT now(),
  updated_at TIMESTAMP NOT NULL DEFAULT now(),
  created_by_uuid TEXT,
  updated_by_uuid TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS pms_form_categories_allocated_no
  ON pms_form_categories (group_uuid, category_no);
CREATE UNIQUE INDEX IF NOT EXISTS pms_form_categories_active_name
  ON pms_form_categories (group_uuid, lower(trim(category_name))) WHERE is_deleted = false;
CREATE INDEX IF NOT EXISTS pms_form_categories_parent_order
  ON pms_form_categories (group_uuid, is_deleted, display_order);
-- Role masters have shipped with both TEXT and native UUID ruid columns.
-- Match the existing reference type without altering the role table. The API
-- continues to use validated canonical UUID strings in either installation.
DO $forms_master$
DECLARE role_reference_type TEXT;
BEGIN
  SELECT format_type(a.atttypid, a.atttypmod) INTO role_reference_type
    FROM pg_attribute a
    WHERE a.attrelid = 'admn_role_master'::regclass AND a.attname = 'ruid'
      AND NOT a.attisdropped;
  IF role_reference_type IS NULL OR role_reference_type NOT IN ('text', 'uuid') THEN
    RAISE EXCEPTION 'Forms Master needs admn_role_master.ruid of type text or uuid; found %', role_reference_type;
  END IF;
  EXECUTE format($table$CREATE TABLE IF NOT EXISTS pms_forms_master (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fmuuid TEXT NOT NULL UNIQUE,
  form_id TEXT NOT NULL UNIQUE,
  scope TEXT NOT NULL,
  vessel_id TEXT REFERENCES vessels(vuuid),
  group_uuid TEXT NOT NULL REFERENCES pms_form_groups(fguuid),
  category_uuid TEXT NOT NULL REFERENCES pms_form_categories(fcuuid),
  form_name TEXT NOT NULL,
  company_form_name TEXT NOT NULL,
  wo_pre_approval BOOLEAN NOT NULL DEFAULT false,
  wo_post_approval BOOLEAN NOT NULL DEFAULT false,
  approver_role_ruid %s REFERENCES admn_role_master(ruid),
  approver_role_label TEXT,
  when_to_use TEXT,
  responsible TEXT,
  typical_jobs TEXT,
  suggested_approver TEXT,
  seed_key TEXT UNIQUE,
  is_default BOOLEAN NOT NULL DEFAULT false,
  is_deleted BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMP NOT NULL DEFAULT now(),
  updated_at TIMESTAMP NOT NULL DEFAULT now(),
  created_by_uuid TEXT,
  updated_by_uuid TEXT
)$table$, role_reference_type);
END $forms_master$;
-- Explicit ASCII whitespace: space, tab, LF, CR, FF, VT. Shared API normalization
-- uses the identical set; trim AFTER collapse handles leading/trailing tabs too.
CREATE UNIQUE INDEX IF NOT EXISTS pms_forms_master_active_name
  ON pms_forms_master (lower(trim(regexp_replace(form_name, '[ ' || chr(9) || chr(10) || chr(13) || chr(12) || chr(11) || ']+', ' ', 'g'))))
  WHERE is_deleted = false;
CREATE INDEX IF NOT EXISTS pms_forms_master_parents
  ON pms_forms_master (group_uuid, category_uuid, is_deleted);
CREATE INDEX IF NOT EXISTS pms_forms_master_category ON pms_forms_master (category_uuid, is_deleted);
CREATE INDEX IF NOT EXISTS pms_forms_master_scope ON pms_forms_master (scope, vessel_id, is_deleted);
CREATE INDEX IF NOT EXISTS pms_form_groups_order ON pms_form_groups (is_deleted, display_order);
