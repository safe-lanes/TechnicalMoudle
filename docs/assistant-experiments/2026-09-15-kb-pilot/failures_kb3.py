"""Run D3 — for EVERY failing run of the work-order suite, attach the exact excerpt text supplied to the model and classify.

Excerpt text = the top-5 hits of the winning module from the SAME index (kb-base = live ids / kb-pilot 916) with the same
embedding model, captured by probe_kb3.py, text[:3000] exactly as retrieval.py builds the excerpt block. Retrieval is
deterministic for a fixed index + embedding (provider repeatability proven 14-Sep, cosine 1.000000), so the three runs of one
question share one excerpt set; as a cross-check the citations returned by each run are compared with the probe's hit list
and any mismatch is printed.

Owner rule (15-Sep): classify a failing run as ANSWER GENERATION only if the condition was in the supplied excerpt text and
the answer dropped it; otherwise RETRIEVAL (the needed content was not in the text the model saw).
"""
import json
import re
import sys

sys.path.insert(0, r"C:\Users\GhaziAnwer\TechnicalMoudle\central-assistant-py\indexer")
from acceptance_wo import CASES, PHRASINGS  # noqa: E402

S = sys.argv[1]
QUESTIONS = {c[0]: c[1] for c in CASES}
QUESTIONS.update({cid: q for cid, q, _r in PHRASINGS})
ex = json.load(open(S + "/kb3-excerpts.json", encoding="utf-8"))


def exkey(q: str, s: str) -> str:
    tag = "kb-base" if s.startswith("A") else "kb-pilot"
    return [k for k in ex if k.endswith(tag) and k.split(" || ")[0][:25] == q[:25]][0]


# judge item  → (regex that identifies it in the verdict 'why', regex that shows it IS present in the excerpt text)
ITEMS = {
    "automatic generation": (r"automatic generation MISSING", r"generated by the system|automatic|daily scan|generated automatically|created automatically"),
    "Generate Now described": (r"Generate Now not described", r"generate now"),
    "Generate Now + Sail Admin": (r"Generate Now block lacks Sail Admin", r"sail admin[\s\S]{0,300}generate now|generate now[\s\S]{0,300}sail admin"),
    "Generate Now + vessel switch": (r"Generate Now block lacks the vessel switch", r"generate now[\s\S]{0,300}switch|switch[\s\S]{0,300}generate now"),
    "per-job Generate WO described": (r"per-job Generate WO not described", r"generate wo"),
    "per-job Generate WO + vessel switch": (r"Generate WO block lacks the vessel switch", r"generate wo[\s\S]{0,400}switch|switch[\s\S]{0,400}generate wo"),
    "user need not create": (r"user need not create MISSING", r"no user action|nobody|by the system|automatic"),
    "note of the other ways": (r"note of the other ways MISSING", r"generate now|generate wo[^.]{0,80}(components|part c)|generated by the system|daily scan|automatic"),
    "unplanned procedure": (r"unplanned procedure MISSING", r"unplanned w\.o"),
}
MUST_LITERAL = {"three-paths": ["unplanned w.o", "generate wo"], "planned-auto": ["job"], "unplanned-plus-note": ["unplanned w.o"]}
RULES = {c[0]: c[7] for c in CASES}
RULES.update({cid: r for cid, _q, r in PHRASINGS})

out = ["# Run D3 — every failing work-order run, with the exact excerpt text supplied to the model", "",
       "Excerpts: top-5 hits of the winning module, text[:3000], from the same index and embedding model as the run (probe_kb3.py). "
       "One excerpt set per question × set (deterministic retrieval); each run's returned citations are cross-checked against it below.", ""]
totals: dict[str, int] = {}
rows = []
printed_excerpts: set[str] = set()
by_q: dict[str, list[str]] = {}
for line in open(S + "/kb3-wo-dump.jsonl", encoding="utf-8"):
    j = json.loads(line)
    v = j["verdict"]
    if v["answer"] and v["citation"] and v["rule"]:
        continue
    cid, s, run = j["case"], j["set"], j["run"]
    q = QUESTIONS[cid]
    exc = ex[exkey(q, s)]
    blob = "\n".join(e["text"] for e in exc).lower()
    why = v["why"]
    resp = j["response"]
    body = (resp.get("response") or "").lower()
    # which judge items failed, and whether each was present in the supplied text
    missing = {name: bool(re.search(pat, blob)) for name, (why_pat, pat) in ITEMS.items() if re.search(why_pat, why)}
    literal_missing = [m for m in MUST_LITERAL[RULES[cid]] if m not in body] if not v["answer"] else []
    # citation cross-check: did the run cite files that the probe did not list?
    probe_files = {re.sub(r"\.pdf$", "", e["file"]) for e in exc}
    cited = {c.get("manual", "") for c in resp.get("citations", [])}
    extra_cited = sorted(c for c in cited if c and not any(c.startswith(p[:40]) for p in probe_files))
    if missing and all(missing.values()):
        cls = "ANSWER GENERATION"
        note = "every dropped item is in the supplied text"
    elif missing and not any(missing.values()):
        cls = "RETRIEVAL"
        note = "none of the dropped items is in the supplied text"
    elif missing:
        cls = "MIXED"
        note = "; ".join(f"{k}: {'in text' if p else 'not in text'}" for k, p in missing.items())
    else:
        cls = "JUDGE LITERAL"
        note = "content rule passed; only the literal must-phrase failed"
    if literal_missing and cls != "JUDGE LITERAL":
        note += f"; also literal must-phrase absent: {literal_missing}"
    totals[cls] = totals.get(cls, 0) + 1
    rows.append(f"| {cid} | {s} | {run} | {cls} | {note} |")
    sec = [f"## {cid} · {s} · run {run} → **{cls}**", f"- question: {q}", f"- judge: answer={v['answer']} citation={v['citation']} rule={v['rule']} — {why}",
           f"- classification note: {note}", f"- citations returned by this run: {sorted(cited)}" + (f"  ⚠ not in probe list: {extra_cited}" if extra_cited else "  (all within the probe's hit list)")]
    ans = re.sub(r"\s+", " ", resp.get("response") or "")
    sec.append(f"- answer (full): {ans}")
    key = f"{cid}|{s}"
    if key not in printed_excerpts:
        printed_excerpts.add(key)
        sec.append(f"- **excerpt text supplied for this question on {s} (identical for runs 1–3):**")
        for e in exc:
            sec.append(f"  - [{e['rank']}] {e['file']} · {e['section']} · {len(e['text'])} chars · d={e.get('distance', '')}")
            sec.append("    ```")
            sec.extend("    " + ln for ln in e["text"].splitlines())
            sec.append("    ```")
    else:
        sec.append(f"- excerpt text: same as run 1 of {cid} on {s} (above)")
    by_q.setdefault(key, []).extend(sec + [""])

out.append("## Totals")
out.append("| classification | failing runs |\n|---|---|")
out.extend(f"| {k} | {n} |" for k, n in sorted(totals.items()))
out += ["", "## Per-run classification", "| case | set | run | classification | note |", "|---|---|---|---|---|"] + rows + [""]
for key, sec in by_q.items():
    out.extend(sec)
open(S + "/kb3-failures.md", "w", encoding="utf-8").write("\n".join(out))
print("\n".join(out[:len(rows) + 12]))
