const quote = (value: string) => `"${value.replaceAll('"', '""')}"`;

async function createFixtureTable(table: any) {
  const config = getTableConfig(table);
  const dialect = new PgDialect();
  const columns = config.columns.map(column => {
    let defaultSql = '';
    if (column.generatedIdentity) defaultSql = ' GENERATED BY DEFAULT AS IDENTITY';
    else if (column.default !== undefined) {
      const value = column.default;
      const type = column.getSQLType();
      const literal = value instanceof SQL ? dialect.sqlToQuery(value).sql
        : type === 'json' || type === 'jsonb' ? `'${JSON.stringify(value).replaceAll("'", "''")}'::${type}`
        : typeof value === 'string' ? `'${value.replaceAll("'", "''")}'`
        : String(value);
      defaultSql = ` DEFAULT ${literal}`;
    }
    return `${quote(column.name)} ${column.getSQLType()}${defaultSql}${column.primary ? ' PRIMARY KEY' : ''}`;
  });
  // No application foreign keys: all records are isolated fixture identities.
  await pool.query(`CREATE TABLE ${quote(config.name)} (${columns.join(', ')})`);
}

async function readJob(id: string) {
  return fixture.storage.getJob(id);
}

async function makeJob(selection: string[] = ['A', 'B']) {
  return createJob({ jobNo: 'TEST', jobTitle: 'Fixture Job', assignedTo: 'Chief Engineer',
    vesselId: 'test-vessel', maintenanceBasis: 'Calendar', officeReviewerRoleRuids: selection,
    nextDueDate: '01-Jan-2027', lastDoneDate: '01-Jan-2026' });
}

async function makeRequest(job: any, proposed: string[] = ['C']) {
  return createChangeRequest({ category: 'jobs', title: 'Fixture change', reason: 'Test',
    vesselId: 'test-vessel', targetType: 'job', targetId: job.juuid, requestedByUserId: 'fixture',
    proposedChangesJson: [{ field: 'officeReviewerRoleRuids', oldValue: job.officeReviewerRoleRuids, newValue: proposed }],
  });
}

beforeAll(async () => {
  // Dedicated, hardcoded fixture endpoint: no DATABASE_URL fallback.
  pool = new Pool({ host: '127.0.0.1', port: 55432, user: 'runner', database: 'postgres' });
  await pool.query('DROP DATABASE IF EXISTS office_reviewer_fixture');
  await pool.query('CREATE DATABASE office_reviewer_fixture');
  await pool.end();
  pool = new Pool({ host: '127.0.0.1', port: 55432, user: 'runner', database: 'office_reviewer_fixture' });
  fixture.pool = pool;
  fixture.db = drizzle(pool, { schema });
  fixture.storage = new PostgresStorage();
});
afterAll(async () => { if (pool) await pool.end(); });

describe.sequential('isolated migration and real ORM / Modify PMS / receiver writes', () => {
  beforeEach(async () => {
    await pool.query('DROP SCHEMA public CASCADE; CREATE SCHEMA public');
    await createFixtureTable(schema.jobs);
    await createFixtureTable(schema.admnRoleMaster);
    await createFixtureTable(schema.changeRequest);
    await createFixtureTable(schema.changeRequestApproval);
    await createFixtureTable(schema.auditLog);
    await fixture.db.insert(schema.admnRoleMaster).values([
      { id: 1, ruid: 'A', assignedRole: 'Reviewer', roletype: 'Office', sortOrder: 1 },
      { id: 42, ruid: 'B', assignedRole: 'Reviewer', roletype: 'Vessel', sortOrder: 2 },
      { id: 77, ruid: 'C', assignedRole: 'Other', roletype: 'Office', sortOrder: 3 },
      { id: 8, ruid: 'inactive', assignedRole: 'Inactive', roletype: 'Office', isActive: false },
    ]);
  });

  it('first and repeat additive migration preserve legacy records, nullable JSONB type and empty default', async () => {
    await pool.query('ALTER TABLE jobs DROP COLUMN office_reviewer_role_ruids');
    await pool.query("INSERT INTO jobs (id, juuid, job_no, level2_reviewer_rank_id) VALUES ('legacy', 'legacy-uuid', 'LEGACY', 'Office')");
    await pool.query(migration);
    await pool.query(migration);
    const meta = await pool.query("SELECT data_type, column_default, is_nullable FROM information_schema.columns WHERE table_name='jobs' AND column_name='office_reviewer_role_ruids'");
    expect(meta.rows[0]).toEqual({ data_type: 'jsonb', column_default: "'[]'::jsonb", is_nullable: 'YES' });
    expect((await pool.query("SELECT job_no, level2_reviewer_rank_id, office_reviewer_role_ruids FROM jobs WHERE id='legacy'")).rows[0])
      .toEqual({ job_no: 'LEGACY', level2_reviewer_rank_id: 'Office', office_reviewer_role_ruids: [] });
    await pool.query("UPDATE jobs SET office_reviewer_role_ruids=NULL WHERE id='legacy'");
    expect(normalizeOfficeReviewerRoleRuids((await readJob('legacy')).officeReviewerRoleRuids)).toEqual([]);
  });

  it('normal SQL discovery and migration tracking apply the file once and skip repeat startup', async () => {
    const root = mkdtempSync(join(tmpdir(), 'reviewer-migration-runner-'));
    mkdirSync(join(root, 'migrations'));
    copyFileSync('migrations/180_jobs_office_reviewer_role_ruids.sql', join(root, 'migrations/180_jobs_office_reviewer_role_ruids.sql'));
    await pool.query('ALTER TABLE jobs DROP COLUMN office_reviewer_role_ruids');
    const cwd = vi.spyOn(process, 'cwd').mockReturnValue(root);
    try {
      expect(await runDrizzleMigrations(pool)).toEqual({ applied: 1, skipped: 0 });
      expect(await runDrizzleMigrations(pool)).toEqual({ applied: 0, skipped: 1 });
      const tracked = await pool.query("SELECT id FROM schema_migrations");
      expect(tracked.rows).toEqual([{ id: '180_jobs_office_reviewer_role_ruids' }]);
    } finally {
      cwd.mockRestore();
      rmSync(root, { recursive: true, force: true });
    }
  });

  it('create and direct replacements round-trip native arrays, clear, preserve omitted values and maintenance tracking', async () => {
    let job = await makeJob();
    await pool.query('UPDATE jobs SET level2_reviewer_rank_id=$1 WHERE juuid=$2', ['Office', job.juuid]);
    const baseline = await readJob(job.juuid);
    for (const selected of [['A', 'C'], ['C'], []]) {
      job = await updateJob(job.juuid, { officeReviewerRoleRuids: selected });
      expect(job.officeReviewerRoleRuids).toEqual(selected);
      expect((await readJob(job.juuid)).officeReviewerRoleRuids).toEqual(selected);
      expect(job.nextDueDate).toBe(baseline.nextDueDate);
      expect(job.lastDoneDate).toBe(baseline.lastDoneDate);
      expect(job.trackingRebaselinedAt).toBeNull();
      expect(job.level2ReviewerRankId).toBe('Office');
      expect(job.updatedAt.getTime()).toBeGreaterThanOrEqual(baseline.updatedAt.getTime());
    }
    await updateJob(job.juuid, { officeReviewerRoleRuids: ['A'] });
    expect((await updateJob(job.juuid, { jobTitle: 'Unrelated' })).officeReviewerRoleRuids).toEqual(['A']);
    const raw = (await pool.query('SELECT jsonb_typeof(office_reviewer_role_ruids) AS type FROM jobs WHERE juuid=$1', [job.juuid])).rows[0];
    expect(raw.type).toBe('array');
    const created = await createJob({ jobNo: 'EMPTY', jobTitle: 'Empty', assignedTo: 'CE', vesselId: 'test-vessel', level2ReviewerRankId: 'Office' });
    expect(created.officeReviewerRoleRuids).toEqual([]);
    expect(created.level2ReviewerRankId).toBeNull();
  });

  it.each(['Office', '["A"]', {}, null, [1], [''], ['A', 'A'], ['inactive'], ['missing']].map(value => ({ value })))(
    'rejects malformed/new invalid selections $value before direct writes', async ({ value }) => {
      const job = await makeJob();
      await expect(updateJob(job.juuid, { officeReviewerRoleRuids: value, jobTitle: 'Must not persist' })).rejects.toThrow();
      expect((await readJob(job.juuid)).officeReviewerRoleRuids).toEqual(['A', 'B']);
      expect((await readJob(job.juuid)).jobTitle).toBe('Fixture Job');
      await expect(createJob({ jobNo: 'INVALID', jobTitle: 'Bad', assignedTo: 'CE', officeReviewerRoleRuids: value })).rejects.toThrow();
    }
  );

  it('retains historic RUIDs when catalogs lag, while rejecting new unavailable selections', async () => {
    const job = await makeJob();
    await pool.query("DELETE FROM admn_role_master WHERE ruid='B'");
    expect((await updateJob(job.juuid, { officeReviewerRoleRuids: ['B', 'A'] })).officeReviewerRoleRuids).toEqual(['A', 'B']);
    expect((await updateJob(job.juuid, { jobTitle: 'Unrelated' })).officeReviewerRoleRuids).toEqual(['A', 'B']);
    expect((await updateJob(job.juuid, { officeReviewerRoleRuids: [] })).officeReviewerRoleRuids).toEqual([]);
    await expect(updateJob(job.juuid, { officeReviewerRoleRuids: ['B'] })).rejects.toThrow();
  });

  it('reuses active/deleted role source ordering, including NULL deletion flags and duplicate names', async () => {
    await fixture.db.insert(schema.admnRoleMaster).values([
      { id: 90, ruid: 'deleted', assignedRole: 'Deleted', roletype: 'Office', isDeleted: true, sortOrder: 0 },
      { id: 91, ruid: 'null-deletion', assignedRole: 'Active', roletype: 'Office', isDeleted: null, sortOrder: 4 },
    ]);
    const roles = await fixture.storage.getActiveRoles();
    expect(roles.map((role: any) => role.ruid)).toEqual(['A', 'B', 'C', 'null-deletion']);
    expect(roles.filter((role: any) => role.assignedRole === 'Reviewer').map((role: any) => role.ruid)).toEqual(['A', 'B']);
  });

  it('Modify PMS keeps arrays proposed until final approval and retains typed audit / original values', async () => {
    const job = await makeJob();
    const request = await makeRequest(job);
    expect((await readJob(job.juuid)).officeReviewerRoleRuids).toEqual(['A', 'B']);
    const result = await approveChangeRequest(request.id, { comment: 'Test approval', role: 'Sail Admin' });
    expect((await readJob(job.juuid)).officeReviewerRoleRuids).toEqual(['C']);
    expect((result.proposedChangesJson as any[])[0].newValue).toEqual(['C']);
    expect(result.revisionHistory[0].appliedChanges[0].newValue).toEqual(['C']);
    expect((await readJob(job.juuid)).nextDueDate).toBe(job.nextDueDate);
  });

  it('reviewer override changes do not alter unrelated scalar editor / override behavior', async () => {
    const job = await makeJob();
    const request = await makeRequest(job);
    await fixture.storage.updateChangeRequest(request.id, { proposedChangesJson: [
      ...(request.proposedChangesJson as any[]), { field: 'jobTitle', oldValue: job.jobTitle, newValue: 'Proposed title' },
    ] });
    await approveChangeRequest(request.id, { comment: 'Mixed approval', role: 'Sail Admin', overriddenChanges: [
      { field: 'officeReviewerRoleRuids', approverNewValue: [] },
      { field: 'jobTitle', approverNewValue: 'Overridden title' },
    ] });
    const result = await readJob(job.juuid);
    expect(result.officeReviewerRoleRuids).toEqual([]);
    expect(result.jobTitle).toBe('Overridden title');
  });

  it.each([undefined, ['B'], []].map(final => ({ final })))('partial overrides retain arrays; final override $final wins, including explicit clear', async ({ final }) => {
    const job = await makeJob();
    const request = await makeRequest(job);
    await fixture.storage.createChangeRequestApprovalStep({ changeRequestId: request.id, changeRequestUuid: request.cruuid, approvalLevel: 'Level 1', status: 'Pending' });
    await fixture.storage.createChangeRequestApprovalStep({ changeRequestId: request.id, changeRequestUuid: request.cruuid, approvalLevel: 'Level 2', status: 'Pending' });
    const partial = await approveChangeRequest(request.id, { comment: 'Partial', role: 'Sail Admin',
      overriddenChanges: [{ field: 'officeReviewerRoleRuids', approverNewValue: [] }] });
    expect(partial.status).not.toBe('approved');
    expect((partial.revisionHistory as any[])[0].overriddenFields[0].approverNewValue).toEqual([]);
    expect((await readJob(job.juuid)).officeReviewerRoleRuids).toEqual(['A', 'B']);
    const result = await approveChangeRequest(request.id, { comment: 'Final', role: 'Sail Admin',
      ...(final === undefined ? {} : { overriddenChanges: [{ field: 'officeReviewerRoleRuids', approverNewValue: final }] }) });
    expect(result.status).toBe('approved');
    expect((await readJob(job.juuid)).officeReviewerRoleRuids).toEqual(final ?? []);
    expect((result.proposedChangesJson as any[])[0].newValue).toEqual(['C']);
    expect(result.revisionHistory.at(-1).appliedChanges[0].newValue).toEqual(final ?? []);
  });

  it('invalid final effective values roll back all Job changes and final approval step', async () => {
    const job = await makeJob();
    const request = await makeRequest(job);
    // Simulate a stored old/malformed request; final transactional validation is mandatory.
    await pool.query('UPDATE change_request SET proposed_changes_json=$1 WHERE id=$2', [JSON.stringify([
      { field: 'jobTitle', newValue: 'Must roll back' },
      { field: 'officeReviewerRoleRuids', oldValue: ['A', 'B'], newValue: 'A,B' },
    ]), request.id]);
    const step = await fixture.storage.createChangeRequestApprovalStep({ changeRequestId: request.id, changeRequestUuid: request.cruuid, approvalLevel: 'Level 1', status: 'Pending' });
    await expect(approveChangeRequest(request.id, { comment: 'Invalid', role: 'Sail Admin' })).rejects.toThrow();
    expect((await readJob(job.juuid)).jobTitle).toBe(job.jobTitle);
    expect((await readJob(job.juuid)).officeReviewerRoleRuids).toEqual(['A', 'B']);
    expect((await fixture.storage.getChangeRequestApprovalSteps(request.id)).find((row: any) => row.id === step.id).status).toBe('Pending');
    expect((await fixture.storage.getChangeRequest(request.id)).status).not.toBe('approved');
  });

  it.each(['rejectChangeRequest', 'returnChangeRequest'])('%s does not change configuration', async action => {
    const job = await makeJob();
    const request = await makeRequest(job);
    await fixture.storage[action](request.id, 'reviewer', 'Test decision', 'Sail Admin');
    expect((await readJob(job.juuid)).officeReviewerRoleRuids).toEqual(['A', 'B']);
  });

  it('older receiver metadata skips the new column; migration alone needs restart and authorized resend', async () => {
    await pool.query('ALTER TABLE jobs DROP COLUMN office_reviewer_role_ruids');
    vi.resetModules();
    const oldReceiver = await import('../server/modules/sync/oneWayApplier');
    const incoming = { id: 'older-local', juuid: 'older-job', job_no: 'OLDER',
      office_reviewer_role_ruids: ['A', 'B'] };
    expect((await oldReceiver.applyOneWayRows('jobs', [incoming])).errors).toEqual([]);
    expect((await pool.query("SELECT job_no FROM jobs WHERE juuid='older-job'")).rows[0].job_no).toBe('OLDER');
    await pool.query(migration);
    expect((await oldReceiver.applyOneWayRows('jobs', [incoming])).errors).toEqual([]);
    expect((await pool.query("SELECT office_reviewer_role_ruids FROM jobs WHERE juuid='older-job'")).rows[0].office_reviewer_role_ruids).toEqual([]);
    // Simulate deploying/restarting the compatible receiver and a targeted resend.
    vi.resetModules();
    const compatibleReceiver = await import('../server/modules/sync/oneWayApplier');
    expect((await compatibleReceiver.applyOneWayRows('jobs', [incoming])).errors).toEqual([]);
    expect((await pool.query("SELECT office_reviewer_role_ruids FROM jobs WHERE juuid='older-job'")).rows[0].office_reviewer_role_ruids).toEqual(['A', 'B']);
  });

  it('real receiver INSERT / UPDATE deliver typed arrays, omit preserves, NULL means none, protected tracking survives', async () => {
    const incoming = { id: 'shore-local-id', juuid: 'sync-job', job_no: 'SYNC', vessel_id: 'test-vessel',
      office_reviewer_role_ruids: ['A', 'B'], next_due_date: '01-Jan-2027', last_done_rh: '500' };
    let result = await applyOneWayRows('jobs', [incoming]);
    expect(result.errors).toEqual([]);
    expect((await readJob('sync-job')).officeReviewerRoleRuids).toEqual(['A', 'B']);
    await pool.query("UPDATE jobs SET id='ship-local-id', last_done_rh='900', next_due_rh='1200' WHERE juuid='sync-job'");
    await pool.query("DELETE FROM admn_role_master WHERE ruid='B'");
    for (const selected of [['B'], []]) {
      result = await applyOneWayRows('jobs', [{ ...incoming, office_reviewer_role_ruids: selected, last_done_rh: '200' }]);
      expect(result.errors).toEqual([]);
      const saved = await readJob('sync-job');
      expect(saved.officeReviewerRoleRuids).toEqual(selected);
      expect(saved.lastDoneRH).toBe('900');
      expect(saved.nextDueRH).toBe('1200');
      expect(saved.trackingRebaselinedAt).toBeNull();
    }
    await applyOneWayRows('jobs', [{ ...incoming, office_reviewer_role_ruids: ['B'] }]);
    await applyOneWayRows('jobs', [{ juuid: 'sync-job', job_title: 'Unrelated incoming field' }]);
    expect((await readJob('sync-job')).officeReviewerRoleRuids).toEqual(['B']);
    await applyOneWayRows('jobs', [{ juuid: 'sync-job', office_reviewer_role_ruids: null }]);
    expect(normalizeOfficeReviewerRoleRuids((await readJob('sync-job')).officeReviewerRoleRuids)).toEqual([]);
  });
});
